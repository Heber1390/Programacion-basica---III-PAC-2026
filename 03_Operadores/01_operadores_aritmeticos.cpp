/* estudiar los diferentes operadores aritmeticos  */

#include <iostream>
using namespace std;        

int main()
{
    // Declaración de variables
    int a = 10;
    int b = 3;

    // Operadores aritméticos
    cout << "Suma: " << a + b << endl;          // Suma
    cout << "Resta: " << a - b << endl;         // Resta
    cout << "Multiplicacion: " << a * b << endl; // Multiplicación
    cout << "Division: " << a / b << endl;      // División
    cout << "Modulo: " << a % b << endl;        // Módulo

    return 0;
}