/* ejemplos de operadores de incremento y decremento  */

#include <iostream>
using namespace std;        

int main()
{
    int x = 5;
    cout << "x = " << x << endl;

    x++;        // Incremento
    cout << "x++ => " << x << endl;

    x--;        // Decremento
    cout << "x-- => " << x << endl;

    return 0;
}   